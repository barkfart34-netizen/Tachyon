//! Tachyon's mod creative kinds. The item-id lists below were derived from
//! Create 6.0.10's MIT sources: AllBlocks, AllItems, AllPaletteBlocks and
//! AllCreatePonderTags, following the registered classes' content packages.
//! See THIRD_PARTY_NOTICES.md for Create's notice. These are names only,
//! not Create's assets; the item registry decides which of them exist.
//!
//! Ponder's overlapping groups are split by use: recipe appliances go in
//! Processing, belts and arms in Logistics, pumps in Fluids, movement anchors
//! in Contraptions, and gauges and display targets in Redstone. Windmill
//! bearings and sails stay with kinetic sources. Casings stay with their
//! machinery rather than the palettes; train doors and seats with contraptions.
//! Building blocks follow the palettes tab and decoration packages.
//!
//! Generated names are expanded from AllPaletteStoneTypes, PaletteBlockPattern,
//! PaletteBlockPartial, WindowGen, MetalBarsGen, CopperBlockSet, the dyed lists
//! in AllBlocks, and PackageStyles.getItemId. Buckets come from AllFluids.

pub(super) struct Kind {
    pub(super) id: &'static str,
    pub(super) title: &'static str,
    pub(super) key: &'static str,
    /// Used only if the registry lists it; otherwise the kind's first item.
    pub(super) icon: &'static str,
    pub(super) items: &'static [&'static str],
}

pub(super) struct ModKinds {
    namespace: &'static str,
    pub(super) kinds: &'static [Kind],
    /// The kind for an item not yet in this mod's table.
    fallback: usize,
}

impl ModKinds {
    pub(super) fn kind_of(&self, item: &str) -> usize {
        self.kinds.iter().position(|k| k.items.contains(&item)).unwrap_or(self.fallback)
    }
}

pub(super) fn for_namespace(namespace: &str) -> Option<&'static ModKinds> {
    MOD_KINDS.iter().find(|m| m.namespace == namespace)
}

pub(super) fn item_group_key(id: &str) -> Option<&'static str> {
    let (namespace, path) = id.split_once(':')?;
    let kind = path.strip_prefix("tachyon_tab/")?;
    for_namespace(namespace)?.kinds.iter().find(|k| k.id == kind).map(|k| k.key)
}

