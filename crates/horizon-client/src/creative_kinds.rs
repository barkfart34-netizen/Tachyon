#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn tables_have_unique_ids_and_icons_of_their_kinds() {
        for table in MOD_KINDS {
            assert!(table.fallback < table.kinds.len());
            let mut kinds = HashSet::new();
            let mut items = HashSet::new();
            for kind in table.kinds {
                assert!(kinds.insert(kind.id), "{}:{}", table.namespace, kind.id);
                assert!(kind.items.contains(&kind.icon));
                for item in kind.items {
                    assert_eq!(item.split_once(':').unwrap().0, table.namespace);
                    assert!(items.insert(item), "{item} has more than one kind");
                }
            }
        }
    }
}
